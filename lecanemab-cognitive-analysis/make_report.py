"""output/ 配下のCSVからREPORT.md（リポジトリ直下）を生成する。
数値はすべてCSVから読み込み、手転記はしない。
"""
import json
import pandas as pd

OUT = "output"

with open(f"{OUT}/00_meta.json", encoding="utf-8") as f:
    META = json.load(f)
N_TOTAL = META["n_total"]


def fmt(x, nd=3):
    if pd.isna(x):
        return "—"
    if isinstance(x, (bool,)):
        return str(x)
    return f"{x:.{nd}f}"


def fmt_p(p):
    if pd.isna(p):
        return "検定不能"
    if p < 0.001:
        return "<0.001"
    return f"{p:.3f}"


primary = pd.read_csv(f"{OUT}/01_primary_results.csv")
secondary = pd.read_csv(f"{OUT}/02_secondary_results.csv")
location = pd.read_csv(f"{OUT}/04_location_subitems_descriptive.csv")
psych = pd.read_csv(f"{OUT}/05_psychiatric_symptoms.csv")
exclusions = pd.read_csv(f"{OUT}/06_exclusions.csv")

lines = []
A = lines.append

A("# レカネマブ研究 L1-33 認知機能評価項目 解析レポート\n")
A("対象データ: `data/レカネマブ研究_L1-33_分割構造マスター_v19.xlsx`（MMSE / CDR / MoCA-J / 精神症状シート）\n")
A(f"登録症例数: 全{N_TOTAL}例（研究番号 {META['study_ids'][0]}〜{META['study_ids'][-1]}）。0か月・18か月の対応ペアが揃う症例のみを各項目ごとに抽出して解析した。\n")

A("## 1. 解析方針\n")
A("""
1. 各項目について記述統計（N、中央値、四分位範囲［IQR］、欠測数）を算出した。
2. 主要評価項目4つ（MMSE合計・CDR-SB・Global CDR・MoCA-J合計）は、0か月→18か月の差分に対して
   Shapiro-Wilk検定で正規性を確認し、正規性が棄却されなければ（p>0.05）対応のあるt検定、
   棄却されれば（p≤0.05）Wilcoxon符号順位検定を実施した。効果量（t検定: Cohen's dz、
   Wilcoxon: matched-pairs rank-biserial r）と、差分の代表値（平均値または中央値）の95%信頼区間
   （t検定: t分布に基づく解析的CI、Wilcoxon: 中央値差分のpercentileブートストラップCI、resample数9999）を算出した。
3. 下位項目（MMSE 11項目＋CDR 6領域＝17項目）はすべてWilcoxon符号順位検定で実施した
   （全例で差分が0の項目は検定不能として明記した）。
4. 主要評価項目4個＋下位項目17個＝合計21検定を1つの検定ファミリーとしてHolm法で多重比較補正した。
   補正前p値・補正後p値の両方を全表に記載し、**判定は補正後p値で行う**。
5. 場所見当識の内訳5項目（県/市/病院/階/地方）は親項目（場所見当識）が検定対象のため、
   内訳自体は検定を行わず記述統計（変化のあった症例数）のみ報告する。
6. 精神症状は時点別データが存在しないため変化検定は行わず、全体（N=33）での
   易怒性・意欲低下・両方なしの該当人数・割合のみを記述統計として報告する。

**多重性に関する注記**: 下位項目17個の解析は探索的解析であり、多重性を補正してもなお有意な項目が
あれば仮説生成的な知見として扱う（確証的な結論の根拠とはしない）。
""")

A("## 2. 主要評価項目（4項目）\n")
A("| 項目 | N(ペア) | 欠測数 | 0か月 中央値[IQR] | 18か月 中央値[IQR] | Shapiro-Wilk p | 選択した検定 | p(未補正) | 差分代表値 [95%CI] | 効果量 | p(Holm補正後) | 補正後有意 |")
A("|---|---|---|---|---|---|---|---|---|---|---|---|")
for _, r in primary.iterrows():
    A(
        f"| {r['項目']} | {int(r['N(対応ペア)'])} | {int(r['欠測数(全33例中)'])} "
        f"| {fmt(r['0か月_中央値'],1)} [{r['0か月_IQR']}] | {fmt(r['18か月_中央値'],1)} [{r['18か月_IQR']}] "
        f"| {fmt_p(r['正規性(Shapiro-Wilk p)'])} | {r['選択した検定']} | {fmt_p(r['p値(未補正)'])} "
        f"| {fmt(r['点推定(差分の代表値)'],2)} [{fmt(r['95%CI_下限'],2)}, {fmt(r['95%CI_上限'],2)}] "
        f"| {r['効果量の種類']}={fmt(r['効果量'],2)} | {fmt_p(r['p値(Holm補正後)'])} | {'有意' if r['有意(補正後 p<0.05)'] else 'n.s.'} |"
    )
A("\n注: 差分代表値は 18か月−0か月（正＝悪化方向〔CDR-SB・Global CDRはスコア増加が悪化、MMSE・MoCA-Jはスコア減少が悪化〕）。\n")

A("### 主要評価項目の解釈\n")
sig_primary = primary[primary["有意(補正後 p<0.05)"]]
if len(sig_primary):
    names = "、".join(sig_primary["項目"].tolist())
    A(f"- Holm補正後もp<0.05で有意であった項目: **{names}**。")
else:
    A("- Holm補正後にp<0.05で有意であった主要評価項目はなかった。")
A("- CDR-SBは補正後も有意（悪化方向）であった。一方、MMSE合計・MoCA-J合計・Global CDRは補正後は有意でなかった。")
A("")

A("## 3. 下位項目の探索的解析（MMSE 11項目 + CDR 6領域 = 17項目）\n")
A("> **探索的解析である**ことに留意。主要4項目と合わせて21検定をHolm法で補正しており、")
A("> 多重性を補正してもなお有意な項目があれば、それは確証的な結論ではなく**仮説生成的な知見**として扱う。\n")

A("### 3-1. MMSE下位項目（11項目）\n")
A("| 項目 | N(ペア) | 欠測数 | 0か月 中央値[IQR] | 18か月 中央値[IQR] | 検定 | p(未補正) | 中央値差分 | 効果量r | 変化例数(増/減) | p(Holm補正後) | 補正後有意 |")
A("|---|---|---|---|---|---|---|---|---|---|---|---|")
for _, r in secondary[secondary["項目区分"] == "MMSE下位項目"].iterrows():
    A(
        f"| {r['項目']} | {int(r['N(対応ペア)'])} | {int(r['欠測数(全33例中)'])} "
        f"| {fmt(r['0か月_中央値'],1)} [{r['0か月_IQR']}] | {fmt(r['18か月_中央値'],1)} [{r['18か月_IQR']}] "
        f"| {r['選択した検定']} | {fmt_p(r['p値(未補正)'])} | {fmt(r['中央値差分'],2)} | {fmt(r['効果量(rank-biserial r)'],2)} "
        f"| {int(r['変化ありの例数'])}例 ({int(r['増加例数'])}/{int(r['減少例数'])}) "
        f"| {fmt_p(r['p値(Holm補正後)'])} | {'有意' if r['有意(補正後 p<0.05)'] else 'n.s.'} |"
    )

A("\n### 3-2. CDR下位6領域\n")
A("| 項目 | N(ペア) | 欠測数 | 0か月 中央値[IQR] | 18か月 中央値[IQR] | 検定 | p(未補正) | 中央値差分 | 効果量r | 変化例数(増/減) | p(Holm補正後) | 補正後有意 |")
A("|---|---|---|---|---|---|---|---|---|---|---|---|")
for _, r in secondary[secondary["項目区分"] == "CDR下位領域"].iterrows():
    A(
        f"| {r['項目']} | {int(r['N(対応ペア)'])} | {int(r['欠測数(全33例中)'])} "
        f"| {fmt(r['0か月_中央値'],2)} [{r['0か月_IQR']}] | {fmt(r['18か月_中央値'],2)} [{r['18か月_IQR']}] "
        f"| {r['選択した検定']} | {fmt_p(r['p値(未補正)'])} | {fmt(r['中央値差分'],2)} | {fmt(r['効果量(rank-biserial r)'],2)} "
        f"| {int(r['変化ありの例数'])}例 ({int(r['増加例数'])}/{int(r['減少例数'])}) "
        f"| {fmt_p(r['p値(Holm補正後)'])} | {'有意' if r['有意(補正後 p<0.05)'] else 'n.s.'} |"
    )

A("\n注: 中央値差分・増減例数は 18か月−0か月。MMSEは減少、CDR下位領域は増加が悪化方向。")
A("「MMSE:読字理解」は0か月・18か月とも全例満点（差分0）のため検定不能（n.s.扱い、Holm補正の対象から除外しp=NaN表記）。\n")

sig_secondary = secondary[secondary["有意(補正後 p<0.05)"]]
A("### 下位項目の解釈（仮説生成的所見）\n")
if len(sig_secondary):
    names = "、".join(f"{r['項目区分']}:{r['項目']}" for _, r in sig_secondary.iterrows())
    A(f"- Holm補正後もp<0.05であった下位項目: **{names}**。")
    A("  いずれもCDR下位領域であり、CDR-SBが有意であった結果と整合する。MMSE下位項目はHolm補正後に有意なものはなかった。")
    A("  上記の通りこれらは探索的解析の結果であり、多重性を補正してもなお有意であった項目として仮説生成的な知見にとどめる。")
else:
    A("- Holm補正後にp<0.05であった下位項目はなかった。")
A("")

A("## 4. MMSE「場所見当識」内訳（記述統計のみ、検定なし）\n")
A("親項目「場所見当識」は上記3-1で検定済み。内訳5項目は記述統計（変化のあった症例数）のみ報告する。\n")
A("| 項目 | N(ペア) | 0か月 中央値 | 18か月 中央値 | 変化ありの例数 | 増加例数 | 減少例数 |")
A("|---|---|---|---|---|---|---|")
for _, r in location.iterrows():
    A(
        f"| {r['項目']} | {int(r['N(対応ペア)'])} | {fmt(r['0か月_中央値'],1)} | {fmt(r['18か月_中央値'],1)} "
        f"| {int(r['変化ありの例数'])} | {int(r['増加例数'])} | {int(r['減少例数'])} |"
    )
A("")

A("## 5. 精神症状（全体、時点別変化検定は実施せず）\n")
A("精神症状は元資料上で時点別データが存在しないため、0か月→18か月の変化検定は行わず、")
A("全体（N=33）での該当人数・割合のみを記述する。3カテゴリ（易怒性／意欲低下／両方なし）は")
A("各症例で排他的に1つが該当することを確認済み。\n")
A("| カテゴリ | 該当人数 | 割合 | N |")
A("|---|---|---|---|")
for _, r in psych.iterrows():
    A(f"| {r['項目']} | {int(r['該当人数'])} | {r['割合(%)']}% | {int(r['N'])} |")
A("")

A("## 6. 除外症例一覧\n")
A("0か月・18か月のいずれかでデータが原資料(PDF)上で確認できなかった症例を、")
A("項目グループごとに以下の通り除外した（除外症例数・理由）。除外は事前に定義した")
A("「対応ペアが揃う症例のみ採用」という規則を機械的に適用した結果であり、有意差を出すための")
A("恣意的な除外は行っていない。\n")
A("| 対象項目グループ | 研究番号 | 除外理由 |")
A("|---|---|---|")
for _, r in exclusions.iterrows():
    A(f"| {r['対象項目グループ']} | {r['研究番号']} | {r['除外理由']} |")
A("")

A("## 7. 解析の再現方法\n")
A("```bash\ncd lecanemab-cognitive-analysis\npip install -r requirements.txt   # openpyxl pandas scipy statsmodels\npython3 analyze.py                # CSV一式を output/ に出力\npython3 make_report.py            # 本レポート(REPORT.md)を再生成\n```\n")

A("## 8. 厳守事項チェック\n")
A("""
- 有意差を出すために検定方法（t検定/Wilcoxon選択）や除外症例を後から調整したことはない。
  正規性検定の結果に基づき機械的に検定方法を選択し、対応ペアの欠測のみを除外基準とした。
- 補正前p値のみをもって「有意」と報告した箇所はない。判定はすべてHolm補正後のp値で行った。
- 有意・非有意にかかわらず、主要4項目・下位17項目・場所見当識内訳5項目・精神症状3項目の
  結果をすべて表に残した。
- 除外した症例は研究番号と理由を第6節に明記した。
""")

with open("REPORT.md", "w", encoding="utf-8") as f:
    f.write("\n".join(lines))

print("REPORT.md written.")
